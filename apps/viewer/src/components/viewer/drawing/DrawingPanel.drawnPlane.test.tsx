function wallBox(): MeshData {
  const positions = new Float32Array([
    0, 0, 0, 10, 0, 0, 10, 10, 0, 0, 10, 0,
    0, 0, 10, 10, 0, 10, 10, 10, 10, 0, 10, 10,
  ]);
  const indices = new Uint32Array([
    0, 1, 2, 0, 2, 3, 4, 6, 5, 4, 7, 6, 0, 4, 5, 0, 5, 1,
    3, 2, 6, 3, 6, 7, 0, 3, 7, 0, 7, 4, 1, 5, 6, 1, 6, 2,
  ]);
  return { expressId: 1, ifcType: 'IfcWall', modelIndex: 0, positions, normals: new Float32Array(positions.length),
    indices, color: [0.5, 0.5, 0.5, 1], geometryClass: 0 };
}
const zero = { x: 0, y: 0, z: 0 }, max = { x: 10, y: 10, z: 10 };
const geometry: GeometryResult = { meshes: [wallBox()], totalTriangles: 12, totalVertices: 8,
  coordinateInfo: { originShift: zero, originalBounds: { min: zero, max }, shiftedBounds: { min: zero, max }, hasLargeCoordinates: false } };

type Plane = { axis: 'down' | 'front' | 'side'; position: number };
function seed(plane: Plane, patch: Partial<ReturnType<typeof useViewerStore.getState>> = {}): void {
  const s = useViewerStore.getState();
  useViewerStore.setState({ ...fixtureModels({ ...fixtureModel('m'), ifcDataStore: null, geometryResult: geometry }),
    modelPlacement: emptyPlacementState(), activeModelId: null, ifcDataStore: null, activeTool: 'select',
    ...getDefaultDrawing2DState(), drawing2DPanelVisible: true,
    sectionPlane: { ...s.sectionPlane, ...plane, flipped: false, enabled: true, custom: undefined }, ...patch });
}

/** A real plan cut, generated by the runtime host and published with its plane. */
async function generatePlan(): Promise<{ drawing: Drawing2D; plane: Drawing2DState['drawing2DPlane'] }> {
  seed({ axis: 'down', position: 50 });
  render(<DrawingRuntimeHost mergedGeometry={geometry} />);
  for (let i = 0; i < 150 && useViewerStore.getState().drawing2DStatus !== 'ready'; i++) {
    await act(async () => { await new Promise((resolve) => setTimeout(resolve, 20)); });
  }
  const { drawing2D, drawing2DPlane } = useViewerStore.getState();
  assert.ok(drawing2D, 'the host generated a drawing');
  cleanup();
  assert.equal(drawing2DPlane?.axis, 'down', 'published with the plan cut');
  return { drawing: drawing2D, plane: drawing2DPlane };
}

const byLabel = (ui: ParentNode, label: string) => {
  const el = ui.querySelector(`[aria-label="${label}"]`);
  assert.ok(el, `a control labelled "${label}"`);
  return el;
};
function openExport(ui: HTMLElement): void {
  // A Radix dropdown opens on pointerdown and portals its items onto document.body.
  const trigger = byLabel(ui, 'Export');
  act(() => trigger.dispatchEvent(new window.PointerEvent('pointerdown', { bubbles: true, cancelable: true, button: 0, pointerType: 'mouse' } as PointerEventInit)));
  click(trigger);
}
function exportItems(): Array<{ label: string; disabled: boolean; el: Element }> {
  return [...document.querySelectorAll('[role="menuitem"]')].map((el) => ({
    label: el.textContent ?? '', disabled: el.getAttribute('aria-disabled') === 'true', el,
  })).filter((i) => /SVG|DXF|PDF|Print/.test(i.label));
}

/** Clicks "Export SVG" and returns the saved file's name and text. */
async function exportSvg(ui: HTMLElement): Promise<{ name: string; svg: string }> {
  const saved: Array<{ name: string; href: string }> = [];
  const blobs = new Map<string, Blob>();
  const proto = window.HTMLAnchorElement.prototype;
  const originalClick = proto.click;
  const originalCreate = URL.createObjectURL;
  proto.click = function (this: HTMLAnchorElement) { saved.push({ name: this.download, href: this.href }); };
  URL.createObjectURL = (obj: Blob | MediaSource) => {
    const url = originalCreate.call(URL, obj);
    if (obj instanceof Blob) blobs.set(url, obj);
    return url;
  };
  try {
    openExport(ui);
    const svgItem = exportItems().find((i) => /SVG/.test(i.label));
    assert.ok(svgItem && !svgItem.disabled, 'Export SVG is enabled');
    click(svgItem.el);
  } finally {
    proto.click = originalClick;
    URL.createObjectURL = originalCreate;
  }
  assert.equal(saved.length, 1, 'one file saved');
  const blob = blobs.get(saved[0].href);
  assert.ok(blob, 'the saved file is a blob');
  return { name: saved[0].name, svg: await blob.text() };
}

/**
 * Opens the PDF dialog with the drawing on screen, runs `meanwhile` (the cut
 * failing, or nothing), then clicks the dialog's Export and returns the names
 * of the files saved within the same, fixed settle window.
 */
async function pdfExportFromOpenDialog(ui: HTMLElement, meanwhile: () => void): Promise<string[]> {
  const saved: string[] = [];
  const proto = window.HTMLAnchorElement.prototype;
  const originalClick = proto.click;
  proto.click = function (this: HTMLAnchorElement) { saved.push(this.download); };
  try {
    openExport(ui);
    const pdfItem = exportItems().find((i) => /PDF/.test(i.label));
    assert.ok(pdfItem && !pdfItem.disabled, 'Download PDF is enabled while the drawing is shown');
    click(pdfItem.el);
    const dialog = document.querySelector('[role="dialog"]');
    assert.ok(dialog, 'the PDF dialog is open');
    act(meanwhile);
    const exportButton = [...dialog.querySelectorAll('button')].find((b) => b.textContent === 'Export');
    assert.ok(exportButton, 'the dialog has an Export button');
    click(exportButton);
    await act(async () => { await new Promise((resolve) => setTimeout(resolve, 1500)); });
  } finally {
    proto.click = originalClick;
  }
  return saved;
}

