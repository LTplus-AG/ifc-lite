/**
 * The Drawing panel exports the drawing it shows, labelled with the cut that
 * drawing was generated at (implicit-state-machines D2/D3).
 *
 * D2: moving the live section plane regenerates WITHOUT a progress overlay, so
 * the previous drawing stays on screen with status `ready` while the cut runs.
 * Export used to read the live plane, writing "section-front-…" for a plan,
 * with the front view's Y flip applied to it.
 *
 * D3: a failed cut keeps the previous drawing in the store but hides it behind
 * the error; the export menu stayed enabled and exported that hidden drawing.
 * Behaviour chosen: export follows what the canvas shows, so it is disabled
 * unless the status is `ready`.
 */
