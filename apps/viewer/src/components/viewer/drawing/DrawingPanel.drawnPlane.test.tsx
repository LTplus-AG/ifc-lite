/** Records every painted `moveTo`/`lineTo` segment and the context transform
 *  calls that place them (the axis flip is a `scale`), as in
 *  `Drawing2DCanvas.section-axis-transform.test.tsx`. */
async function paintedSegments(): Promise<string[]> {
  const segments: string[] = [];
  let pen: [number, number] | null = null;
  const ctx = new Proxy({}, {
    get(_target, prop) {
      if (prop === 'measureText') return (text: string) => ({ width: String(text).length * 7 });
      if (prop === 'canvas') return { width: 800, height: 600 };
      if (prop === 'scale' || prop === 'translate' || prop === 'setTransform') {
        return (...args: number[]) => { segments.push(`${String(prop)}(${args.map((v) => v.toFixed(3)).join(',')})`); };
      }
      if (prop === 'moveTo') return (x: number, y: number) => { pen = [x, y]; };
      if (prop === 'lineTo') return (x: number, y: number) => {
        if (pen) segments.push(`${pen[0].toFixed(3)},${pen[1].toFixed(3)}->${x.toFixed(3)},${y.toFixed(3)}`);
        pen = [x, y];
      };
      return () => undefined;
    },
    set() { return true; },
  }) as unknown as CanvasRenderingContext2D;
  const original = HTMLCanvasElement.prototype.getContext;
  HTMLCanvasElement.prototype.getContext = ((kind: string) =>
    kind === '2d' ? ctx : null) as unknown as typeof HTMLCanvasElement.prototype.getContext;
  try {
    render(<DrawingPanel />);
    await act(async () => { await new Promise((resolve) => setTimeout(resolve, 50)); });
  } finally {
    HTMLCanvasElement.prototype.getContext = original;
  }
  cleanup();
  return segments;
}

beforeEach(() => seed({ axis: 'down', position: 50 }));
afterEach(() => cleanup());

it('D2: moving the cut while the plan is still shown exports that plan, labelled as the plan', async () => {
  const { drawing, plane } = await generatePlan();
  const shown = { drawing2D: drawing, drawing2DPlane: plane, drawing2DStatus: 'ready' as const };

  // The live plane matches the drawing: the reference export.
  seed({ axis: 'down', position: 50 }, shown);
  const expected = await exportSvg(render(<DrawingPanel />));
  cleanup();
  assert.equal(expected.name, 'section-down-50.svg');

  // The user moved the cut to a front section; the regenerate has not landed,
  // so the plan is still on screen with status `ready`.
  seed({ axis: 'front', position: 20 }, shown);
  const during = await exportSvg(render(<DrawingPanel />));
  assert.equal(during.svg, expected.svg, 'the plan is not given the front view\'s axis flip');
  assert.equal(during.name, expected.name, 'the file is named for the cut it contains');
});

it('D3: a failed cut disables export of the drawing it hid', async () => {
  const { drawing, plane } = await generatePlan();
  seed({ axis: 'down', position: 50 }, {
    drawing2D: drawing, drawing2DPlane: plane, drawing2DStatus: 'error', drawing2DError: 'Generation failed',
  });
  const ui = render(<DrawingPanel />);
  assert.match(ui.textContent ?? '', /Generation failed/, 'the error replaces the drawing');
  openExport(ui);
  const files = exportItems();
  assert.equal(files.length, 4);
  assert.deepEqual(files.filter((i) => !i.disabled).map((i) => i.label), [], 'no file export of the hidden drawing');
});

it('D2: moving the cut while the plan is still shown keeps painting the plan unflipped', async () => {
  const { drawing, plane } = await generatePlan();
  const shown = { drawing2D: drawing, drawing2DPlane: plane, drawing2DStatus: 'ready' as const };
  seed({ axis: 'down', position: 50 }, shown);
  const expected = await paintedSegments();
  assert.ok(expected.length > 0, 'the plan was painted');
  seed({ axis: 'front', position: 20 }, shown);
  assert.deepEqual(await paintedSegments(), expected, 'the canvas keeps the plan\'s axis until the new cut lands');
});

it('D3: a cut that fails while the PDF dialog is open exports nothing', async () => {
  const { drawing, plane } = await generatePlan();
  const shown = { drawing2D: drawing, drawing2DPlane: plane, drawing2DStatus: 'ready' as const };

  // Control: the same steps with the drawing still shown write the PDF.
  seed({ axis: 'down', position: 50 }, shown);
  assert.deepEqual(await pdfExportFromOpenDialog(render(<DrawingPanel />), () => {}), ['section-down-50-1-100.pdf']);
  cleanup();

  seed({ axis: 'down', position: 50 }, shown);
  const saved = await pdfExportFromOpenDialog(render(<DrawingPanel />), () => {
    useViewerStore.getState().setDrawing2DError('Generation failed');
  });
  assert.deepEqual(saved, [], 'the hidden previous drawing is not exported');
});
