import proj4 from 'proj4';
import { isWktDefinition, registeredWktDefinition, wktDefinitionInMetres } from './wkt-projection';

/** Also answers for a WKT definition registered by `resolveWktProjection`. */
export function isGeographicProj4(definition: string): boolean {
  if (isWktDefinition(definition)) return registeredWktDefinition(definition)?.projName === 'longlat';
  return /\+proj=longlat\b/.test(definition);
}

export function utmProj4String(zone: string): string | null {
  const match = zone.match(/^(\d{1,2})([NS])$/i);
  if (!match) return null;
  const zoneNumber = parseInt(match[1], 10);
  if (zoneNumber < 1 || zoneNumber > 60) return null;
  return `+proj=utm +zone=${zoneNumber}${match[2].toUpperCase() === 'N' ? '' : ' +south'} +datum=WGS84 +units=m +no_defs`;
}

/**
 * Geometry and spatial references carry projected distances in metres. PROJ
 * strings instead describe the CRS's native output unit (e.g. US survey ft).
 * Override that unit at the metre-coordinate boundary; projection offsets
 * +x_0/+y_0 are already metres and must remain untouched.
 * https://proj.org/en/stable/usage/projections.html#projection-units
 */
export function projectedDefinitionInMetres(definition: string): string {
  if (isGeographicProj4(definition)) return definition;
  if (isWktDefinition(definition)) return wktDefinitionInMetres(definition);
  return `${definition.replace(/(?:^|\s)\+(?:units|to_meter)=\S+/g, '').trim()} +units=m`;
}

/** WGS84 semi-major axis (m) and first eccentricity squared. */
const WGS84_A = 6378137;
const WGS84_E2 = 0.0066943799901413165;

/**
 * Radii of curvature of the WGS84 ellipsoid at a geodetic latitude (degrees):
 * `meridian` (M, north-south) and `primeVertical` (N, east-west; a parallel of
 * latitude has radius N cos(lat)).
 */
export function wgs84RadiiOfCurvature(latDeg: number): { meridian: number; primeVertical: number } {
  const s = Math.sin((latDeg * Math.PI) / 180);
  const w = 1 - WGS84_E2 * s * s;
  return { meridian: (WGS84_A * (1 - WGS84_E2)) / (w * Math.sqrt(w)), primeVertical: WGS84_A / Math.sqrt(w) };
}

/** True-north ENU metres (on the WGS84 ellipsoid) of a short step between two WGS84 positions. */
function enuStep(lon1: number, lat1: number, lon2: number, lat2: number): { east: number; north: number } {
  const { meridian, primeVertical } = wgs84RadiiOfCurvature((lat1 + lat2) / 2);
  let dLon = lon2 - lon1;
  if (dLon > 180) dLon -= 360;
  else if (dLon < -180) dLon += 360;
  const rad = Math.PI / 180;
  return {
    east: dLon * rad * primeVertical * Math.cos(((lat1 + lat2) / 2) * rad),
    north: (lat2 - lat1) * rad * meridian,
  };
}

/** Local map-projection factors at one grid point, as seen from the WGS84 ellipsoid. */
export interface GridPointFactors {
  /** Meridian convergence, radians; same convention as {@link computeGridConvergence}. */
  gamma: number;
  /**
   * Point scale factor k: grid distance / WGS84-ellipsoid distance for a short
   * step (geometric mean of the grid-east and grid-north steps, which agree
   * for a conformal projection). Includes the datum shift's own scale, so it
   * is the factor between grid metres and metres on the ellipsoid Cesium uses.
   */
  pointScale: number;
}

/** Half-length (projected metres) of the central-difference probe. */
const PROBE_STEP_M = 10;

/**
 * Convergence and point scale at a projected point by central differences
 * through proj4, measured with the WGS84 meridian (M) and prime-vertical (N)
 * radii. Works for any projection without per-projection formulae. Throws
 * when proj4 does; returns null for non-finite results.
 *
 * Accuracy: the central difference over +/-10 m leaves a truncation term of
 * order (10 m / R)^2, about 1e-12, and the double-precision round-off on the
 * differenced latitudes is about 1e-10. Both outputs match PROJ to 5e-11 on
 * TM, LCC and Krovak (`__fixtures__/proj-oracle.json`, generated by
 * `scripts/geo/generate-proj-oracle.py`).
 */
export function computeGridPointFactors(projDef: string, easting: number, northing: number): GridPointFactors | null {
  const def = projectedDefinitionInMetres(projDef);
  const d = PROBE_STEP_M;
  const [lonS, latS] = proj4(def, 'WGS84', [easting, northing - d]);
  const [lonN, latN] = proj4(def, 'WGS84', [easting, northing + d]);
  const [lonW, latW] = proj4(def, 'WGS84', [easting - d, northing]);
  const [lonE, latE] = proj4(def, 'WGS84', [easting + d, northing]);
  if (![lonS, latS, lonN, latN, lonW, latW, lonE, latE].every(Number.isFinite)) return null;
  const north = enuStep(lonS, latS, lonN, latN);
  const east = enuStep(lonW, latW, lonE, latE);
  const northLength = Math.hypot(north.east, north.north);
  const eastLength = Math.hypot(east.east, east.north);
  if (!(northLength > 0) || !(eastLength > 0)) return null;
  return {
    // grid-north's bearing measured from true north is atan2(east, north) = -gamma.
    gamma: Math.atan2(-north.east, north.north),
    pointScale: Math.sqrt(((2 * d) / northLength) * ((2 * d) / eastLength)),
  };
}

/**
 * Grid (meridian) convergence at a point in a projected CRS: the angle between
 * grid north (the projected CRS's +N axis) and true north (the geographic ENU
 * +N axis). Returned in radians, counter-clockwise positive, such that the grid
 * frame equals the true-ENU frame rotated by +gamma.
 *
 * WHY THIS EXISTS: `IfcMapConversion` aligns the model to GRID north (its
 * XAxisAbscissa/Ordinate are expressed in the projected grid), but Cesium's
 * `eastNorthUpToFixedFrame()` builds a TRUE-north ENU frame. Feeding the
 * grid-aligned model straight into that frame rotates it by the convergence —
 * up to ~3° for UTM near a zone edge, ~7-8° for oblique projections like
 * Krovak (EPSG:2065, S-JTSK / Czech Republic). See issue #1408.
 *
 * Computed by finite difference through proj4 ({@link computeGridPointFactors})
 * so it works for any projection (TM, LCC, Krovak, ...) without per-projection
 * convergence formulae. A geographic (longlat) def has zero convergence by
 * definition. The step is measured on the WGS84 ellipsoid: the spherical
 * 111320 m/degree it used before turned a 2.2° UTM convergence into an angle
 * off by 1e-4 rad (7.6 mm per 100 m).
 */
export function computeGridConvergence(projDef: string, easting: number, northing: number, lat: number): number {
  return computeGridFrame(projDef, easting, northing, lat).gamma;
}

/**
 * {@link computeGridPointFactors} with the placement's guards: a geographic
 * CRS, a point within 0.1° of a pole, or a failed probe read as convergence 0
 * and point scale 1 (the probe failure is logged, see below).
 */
export function computeGridFrame(projDef: string, easting: number, northing: number, lat: number): GridPointFactors {
  const neutral: GridPointFactors = { gamma: 0, pointScale: 1 };
  // Geographic CRS: lat/lon is already true-north aligned.
  if (isGeographicProj4(projDef)) return neutral;
  // Near the poles the local east/metre scale degenerates; skip.
  if (Math.abs(lat) >= 89.9) return neutral;
  try {
    return computeGridPointFactors(projDef, easting, northing) ?? neutral;
  } catch (err) {
    // Zero is not a neutral answer here: it is indistinguishable from a
    // genuinely zero convergence, so the model silently keeps its GRID
    // alignment inside Cesium's TRUE-north ENU frame — a rotation of up to ~3°
    // (UTM zone edge) or ~7-8° (Krovak). Called once per model, so logging it
    // costs nothing and names the cause if it ever happens.
    console.warn(
      `[cesium] grid convergence unavailable for ${projDef}; the model is placed `
      + 'grid-aligned in a true-north frame (rotation up to a few degrees).',
      err,
    );
    return neutral;
  }
}
