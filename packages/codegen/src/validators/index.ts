/** Validator generation: EXPRESS schema -> schema tables, compiled rules and zod schemas for `@ifc-lite/validate`. */

import { parseExpressRules } from '../express/declaration-parser.js';
import { emitSchemaMeta } from './meta-emitter.js';
import { compileRules, type RuleCompilation, type UnsupportedEntry } from './rules-emitter.js';
import { SchemaIndex } from './schema-index.js';
import { emitZodSchemas } from './zod-emitter.js';

export type { UnsupportedEntry } from './rules-emitter.js';

export interface ValidatorGeneratorOptions {
  /** Module specifier of the `@ifc-lite/validate` runtime, as seen from the output directory. */
  runtimeImport?: string;
  /** Module specifier of zod. */
  zodImport?: string;
}

export interface ValidatorCoverage {
  schema: string;
  counts: RuleCompilation['counts'];
  unsupported: UnsupportedEntry[];
}

export interface GeneratedValidators {
  /** File name -> contents. */
  files: Record<string, string>;
  coverage: ValidatorCoverage;
}

const HEADER = (schema: string) => `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */

/* Generated by @ifc-lite/codegen from the EXPRESS schema ${schema}. Do not edit. */
/* eslint-disable */`;

export function generateValidators(expressSource: string, options: ValidatorGeneratorOptions = {}): GeneratedValidators {
  const runtimeImport = options.runtimeImport ?? '@ifc-lite/validate/runtime';
  const zodImport = options.zodImport ?? 'zod';
  const index = new SchemaIndex(parseExpressRules(expressSource));
  const header = HEADER(index.schema.name);
  const schema = emitSchemaMeta(index, header, runtimeImport);
  const rules = compileRules(index, header, runtimeImport);
  const coverage: ValidatorCoverage = { schema: index.schema.name, counts: rules.counts, unsupported: rules.unsupported };
  const files: Record<string, string> = {
    'schema.ts': schema,
    'rules.ts': rules.source,
    'zod.ts': emitZodSchemas(index, header, runtimeImport, zodImport),
    'index.ts': `${header}
import { SchemaRuntime } from '${runtimeImport}';
import { META } from './schema.js';
import { RULES } from './rules.js';

export const SCHEMA = new SchemaRuntime(META, RULES);
`,
    'coverage.json': `${JSON.stringify(coverage, null, 2)}\n`,
  };
  return { files, coverage };
}
