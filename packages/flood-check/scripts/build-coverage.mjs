/**
 * Regenerates src/bafu/coverage-data.ts: the perimeter the BAFU map covers
 * (Switzerland, with the Büsingen and Campione enclaves as holes, and
 * Liechtenstein), from swissBOUNDARIES3D national boundaries on the
 * geo.admin.ch API, simplified with Douglas-Peucker at EPSILON metres and
 * rounded to whole metres. Every original vertex lies within EPSILON of the
 * simplified boundary and every simplified edge within EPSILON of the
 * original, so with rounding the boundary is known to TOLERANCE metres.
 *
 *   node packages/flood-check/scripts/build-coverage.mjs
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const EPSILON = 50;
const TOLERANCE = EPSILON + 1; // + up to 0.71 m from rounding to whole metres
const LAYER = 'ch.swisstopo.swissboundaries3d-land-flaeche.fill';
const url = (id) => `https://api3.geo.admin.ch/rest/services/api/MapServer/${LAYER}/${id}?geometryFormat=geojson&sr=2056`;

function simplify(pts, eps) {
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const dx = bx - ax;
    const dy = by - ay;
    const l2 = dx * dx + dy * dy;
    let best = -1;
    let bi = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const t = l2 === 0 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / l2));
      const d = Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
      if (d > best) {
        best = d;
        bi = i;
      }
    }
    if (best > eps) {
      keep[bi] = 1;
      stack.push([a, bi], [bi, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

function simplifyRing(ring) {
  const open = ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1] ? ring.slice(0, -1) : ring;
  const h = open.length >> 1;
  const a = simplify(open.slice(0, h + 1), EPSILON);
  const b = simplify([...open.slice(h), open[0]], EPSILON);
  return [...a, ...b.slice(1, -1)].map(([x, y]) => [Math.round(x), Math.round(y)]);
}

function encode(ring) {
  const out = [`${ring[0][0]},${ring[0][1]}`];
  for (let i = 1; i < ring.length; i++) out.push(`${ring[i][0] - ring[i - 1][0]},${ring[i][1] - ring[i - 1][1]}`);
  return out.join(',');
}

const rings = [];
for (const id of ['CH', 'LI']) {
  const response = await fetch(url(id));
  if (!response.ok) throw new Error(`${id}: HTTP ${response.status}`);
  const geometry = (await response.json()).feature.geometry;
  const polygons = geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates];
  for (const polygon of polygons) for (const ring of polygon) rings.push(simplifyRing(ring));
}

const target = fileURLToPath(new URL('../src/bafu/coverage-data.ts', import.meta.url));
writeFileSync(
  target,
  `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */

/**
 * GENERATED by scripts/build-coverage.mjs on ${new Date().toISOString().slice(0, 10)}; do not edit.
 *
 * Perimeter of the BAFU surface-runoff map: Switzerland (enclaves Büsingen
 * and Campione as holes) and Liechtenstein, EPSG:2056, from
 * swissBOUNDARIES3D (layer ${LAYER}, © swisstopo),
 * Douglas-Peucker at ${EPSILON} m, whole metres. ${rings.reduce((n, r) => n + r.length, 0)} vertices in ${rings.length} rings.
 * Each ring: first vertex absolute, then deltas, as x,y pairs. Even-odd fill.
 */

/** How far the encoded boundary may lie from the real one, metres. */
export const BAFU_COVERAGE_TOLERANCE = ${TOLERANCE};

export const BAFU_COVERAGE_RINGS: readonly string[] = [
${rings.map((r) => `  '${encode(r)}',`).join('\n')}
];
`,
);
console.log(`wrote ${target}: ${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} vertices`);
