// #8019: audited IFC4/IFC4X3 IfcDistributionElement occurrence descendants
// absent from IFC2X3, grouped by their nearest native IFC2X3 ancestor.
// Preserve the existing distribution-board -> distribution-point semantic
// rename (including IFC4X3's board). Type objects are deliberately excluded.
// Explicit scope: never apply an ancestor fallback to arbitrary unknown types.
pub(crate) fn ifc2x3_type(t: &str) -> Option<&'static str> {
    Some(match t {
        "IFCACTUATOR" | "IFCALARM" | "IFCCONTROLLER"
        | "IFCFLOWINSTRUMENT" | "IFCPROTECTIVEDEVICETRIPPINGUNIT" | "IFCSENSOR"
        | "IFCUNITARYCONTROLELEMENT" => "IFCDISTRIBUTIONCONTROLELEMENT",
        "IFCAIRTERMINAL" | "IFCAUDIOVISUALAPPLIANCE" | "IFCCOMMUNICATIONSAPPLIANCE"
        | "IFCELECTRICAPPLIANCE" | "IFCFIRESUPPRESSIONTERMINAL" | "IFCLAMP"
        | "IFCLIGHTFIXTURE" | "IFCLIQUIDTERMINAL" | "IFCMEDICALDEVICE"
        | "IFCMOBILETELECOMMUNICATIONSAPPLIANCE" | "IFCOUTLET" | "IFCSANITARYTERMINAL"
        | "IFCSIGNAL" | "IFCSPACEHEATER" | "IFCSTACKTERMINAL"
        | "IFCWASTETERMINAL" => "IFCFLOWTERMINAL",
        "IFCAIRTERMINALBOX" | "IFCDAMPER" | "IFCELECTRICTIMECONTROL"
        | "IFCFLOWMETER" | "IFCPROTECTIVEDEVICE" | "IFCSWITCHINGDEVICE"
        | "IFCVALVE" => "IFCFLOWCONTROLLER",
        "IFCAIRTOAIRHEATRECOVERY" | "IFCBOILER" | "IFCBURNER"
        | "IFCCHILLER" | "IFCCOIL" | "IFCCONDENSER"
        | "IFCCOOLEDBEAM" | "IFCCOOLINGTOWER" | "IFCELECTRICGENERATOR"
        | "IFCELECTRICMOTOR" | "IFCENGINE" | "IFCEVAPORATIVECOOLER"
        | "IFCEVAPORATOR" | "IFCHEATEXCHANGER" | "IFCHUMIDIFIER"
        | "IFCMOTORCONNECTION" | "IFCSOLARDEVICE" | "IFCTRANSFORMER"
        | "IFCTUBEBUNDLE" | "IFCUNITARYEQUIPMENT" => "IFCENERGYCONVERSIONDEVICE",
        "IFCCABLECARRIERFITTING" | "IFCCABLEFITTING" | "IFCDUCTFITTING"
        | "IFCJUNCTIONBOX" | "IFCPIPEFITTING" => "IFCFLOWFITTING",
        "IFCCABLECARRIERSEGMENT" | "IFCCABLESEGMENT" | "IFCCONVEYORSEGMENT"
        | "IFCDUCTSEGMENT" | "IFCPIPESEGMENT" => "IFCFLOWSEGMENT",
        "IFCCOMPRESSOR" | "IFCFAN" | "IFCPUMP" => "IFCFLOWMOVINGDEVICE",
        "IFCDISTRIBUTIONBOARD" | "IFCELECTRICDISTRIBUTIONBOARD" => "IFCELECTRICDISTRIBUTIONPOINT",
        "IFCDUCTSILENCER" | "IFCELECTRICFLOWTREATMENTDEVICE" | "IFCFILTER"
        | "IFCINTERCEPTOR" => "IFCFLOWTREATMENTDEVICE",
        "IFCELECTRICFLOWSTORAGEDEVICE" | "IFCTANK" => "IFCFLOWSTORAGEDEVICE",
        _ => return None,
    })
}

