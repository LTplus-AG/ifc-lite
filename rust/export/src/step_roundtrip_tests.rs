// ── Proof the comparison can fail ───────────────────────────────────────────
//
// A round trip that cannot fail is the same defect one level up, and this one
// runs against a writer that copies most entity lines through verbatim — the
// configuration in which a vacuous pass is easiest to mistake for a real one.
// Each test below perturbs the WRITER's output, through options the writer
// already supports, and asserts a specific facet of `first_difference` reports
// it. They are the reason a green run above means something.

/// Identity: change one product's GlobalId on the way out.
#[test]
fn a_changed_global_id_is_caught() {
    let content = fixture_or_skip!("ifcopenshell/1269--Project_IfcDuctFitting.ifc");
    let before = snapshot(&content);
    let victim = before
        .model
        .entities
        .iter()
        .find(|r| r.global_id.is_some())
        .expect("the file must have at least one product with a GlobalId");

    let written = export_step(
        &content,
        &StepOptions {
            attribute_mutations: vec![AttrMutation {
                express_id: victim.express_id,
                index: 0,
                value: "'0zzzzzzzzzzzzzzzzzzzzz'".to_string(),
            }],
            ..StepOptions::default()
        },
    );
    let diff = first_difference(&before, &snapshot(written.as_bytes()))
        .expect("a rewritten GlobalId must be caught");
    assert!(
        diff.contains("GlobalId"),
        "the difference must name the GlobalId, got: {diff}"
    );
}

/// Content: add a property set the source never had.
#[test]
fn an_added_property_set_is_caught() {
    let content = fixture_or_skip!("ifcopenshell/1269--Project_IfcDuctFitting.ifc");
    let before = snapshot(&content);
    let victim = before
        .model
        .entities
        .iter()
        .find(|r| r.global_id.is_some())
        .expect("the file must have at least one product with a GlobalId");

    let written = export_step(
        &content,
        &StepOptions {
            property_mutations: vec![PropMutation {
                express_id: victim.express_id,
                pset_name: "Pset_NotInTheSource".to_string(),
                prop_name: "Invented".to_string(),
                value: "IFCLABEL('x')".to_string(),
            }],
            ..StepOptions::default()
        },
    );
    assert!(
        first_difference(&before, &snapshot(written.as_bytes())).is_some(),
        "a property set that is not in the source must be caught"
    );
}

/// Georeference: move the map conversion's false easting by one metre.
///
/// This is the facet a self-round-trip could never have exercised, because no
/// fixture written here would have carried an authored `IfcMapConversion` in
/// the first place. `Eastings` is attribute index 2 of `IfcMapConversion`
/// (SourceCRS, TargetCRS, Eastings, …).
#[test]
fn a_moved_georeference_is_caught() {
    let content = fixture_or_skip!("buildingsmart/Building-Architecture.ifc");
    let before = snapshot(&content);
    let eastings = before
        .georef
        .as_ref()
        .expect(
            "this file is in the set BECAUSE it is georeferenced; if that stopped \
             being true the georeference comparison above would be running on nothing",
        )
        .eastings;

    let mut scanner = EntityScanner::new(&content);
    let mut map_conversion = None;
    while let Some((id, type_name, _s, _e)) = scanner.next_entity() {
        if type_name.eq_ignore_ascii_case("IFCMAPCONVERSION") {
            map_conversion = Some(id);
            break;
        }
    }
    let map_conversion = map_conversion.expect("georeferenced file must hold an IfcMapConversion");

    let moved = eastings + 1.0;
    let written = export_step(
        &content,
        &StepOptions {
            attribute_mutations: vec![AttrMutation {
                express_id: map_conversion,
                index: 2,
                value: format!("{moved:?}"),
            }],
            ..StepOptions::default()
        },
    );
    let diff = first_difference(&before, &snapshot(written.as_bytes()))
        .expect("a moved false easting must be caught");
    assert!(
        diff.contains("georeference"),
        "the difference must name the georeference, got: {diff}"
    );
}

/// Structure: drop an entity the source had.
///
/// Exported as a subset that excludes one record, which is the closest the
/// writer's own options come to the failure the census exists to catch — a
/// record the scanner silently fails to re-emit. An
/// `IfcRelDefinesByProperties` is chosen because nothing references one, so the
/// forward closure cannot pull it back in.
#[test]
fn a_dropped_entity_is_caught() {
    let content = fixture_or_skip!("ifcopenshell/1269--Project_IfcDuctFitting.ifc");
    let before = snapshot(&content);

    let mut scanner = EntityScanner::new(&content);
    let mut keep = Vec::new();
    let mut dropped = None;
    while let Some((id, type_name, _s, _e)) = scanner.next_entity() {
        if dropped.is_none() && type_name.eq_ignore_ascii_case("IFCRELDEFINESBYPROPERTIES") {
            dropped = Some(id);
            continue;
        }
        keep.push(id);
    }
    assert!(
        dropped.is_some(),
        "file must hold an IfcRelDefinesByProperties"
    );

    let written = export_step(
        &content,
        &StepOptions {
            included: Some(keep),
            ..StepOptions::default()
        },
    );
    let diff = first_difference(&before, &snapshot(written.as_bytes()))
        .expect("an entity missing from the output must be caught");
    assert!(
        diff.contains("IFCRELDEFINESBYPROPERTIES") || diff.contains("property sets"),
        "the difference must name the dropped record or the properties it \
         carried, got: {diff}"
    );
}

// ── Subset export over third-party input ────────────────────────────────────

/// A filtered export of a third-party file must not dangle a reference.
///
/// The reference closure is the one part of the writer that is not a
/// passthrough, and it has only ever been exercised on files written here. A
/// real file references through constructs a hand-written fixture does not use
/// — mapped items, presentation layer assignments, styled item chains — and
/// every one of them has to be pulled in or the output is unreadable.
#[test]
fn subset_export_of_third_party_products_dangles_no_reference() {
    let content = fixture_or_skip!("ara3d/AC20-FZK-Haus.ifc");

    let mut total = 0usize;
    let mut roots = Vec::new();
    let mut scanner = EntityScanner::new(&content);
    while let Some((id, type_name, _s, _e)) = scanner.next_entity() {
        total += 1;
        if type_name.eq_ignore_ascii_case("IFCWALLSTANDARDCASE")
            || type_name.eq_ignore_ascii_case("IFCWALL")
        {
            roots.push(id);
        }
    }
    assert!(
        !roots.is_empty(),
        "the file must hold walls, or this test filters on nothing"
    );

    let written = export_step(
        &content,
        &StepOptions {
            included: Some(roots.clone()),
            ..StepOptions::default()
        },
    );

    let out_bytes = written.as_bytes();
    let mut present: HashSet<u32> = HashSet::new();
    let mut lines: Vec<(u32, usize, usize)> = Vec::new();
    let mut out_scanner = EntityScanner::new(out_bytes);
    while let Some((id, _t, s, e)) = out_scanner.next_entity() {
        present.insert(id);
        lines.push((id, s, e));
    }

    assert!(
        present.len() < total,
        "a subset that emitted all {total} entities proves nothing about the closure"
    );
    for root in &roots {
        assert!(
            present.contains(root),
            "#{root} was asked for but is not in the subset"
        );
    }

    let mut refs = Vec::new();
    for (id, s, e) in &lines {
        refs.clear();
        crate::step_text::refs_in_line(&out_bytes[*s..*e], &mut refs);
        for r in &refs {
            assert!(
                present.contains(r),
                "#{id} in the subset references #{r}, which the closure did not emit"
            );
        }
    }
}
