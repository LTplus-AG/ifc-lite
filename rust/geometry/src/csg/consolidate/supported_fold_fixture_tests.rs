fn actual_source() -> Mesh {
    let mut mesh = Mesh::new();
    for bits in SOURCE {
        let t = bits.map(|p| Point3::from(p.map(|b| f64::from(f32::from_bits(b)))));
        let normal = (t[1] - t[0]).cross(&(t[2] - t[0])).normalize();
        append(&mut mesh, &t, &normal);
    }
    mesh.plane_tags = None;
    mesh
}

// Independent strict-interior point containment: exact plane incidence and
// exact projected edge signs, with a positive raw-source control below.
fn strict_hits(mesh: &Mesh, point: [f64; 3]) -> usize {
    mesh.indices.chunks_exact(3).filter(|tri| {
        let t = [tri[0], tri[1], tri[2]].map(|i| {
            [0, 1, 2].map(|k| f64::from(mesh.positions[i as usize * 3 + k]))
        });
        if crate::kernel::predicates::orient3d_explicit(t[0],t[1],t[2],point)
            != crate::kernel::Sign::Zero { return false; }
        let a = Point3::from(t[0]);
        let n = (Point3::from(t[1]) - a).cross(&(Point3::from(t[2]) - a)).map(f64::abs);
        let (x,y) = if n.x >= n.y && n.x >= n.z { (1,2) }
            else if n.y >= n.z { (2,0) } else { (0,1) };
        let p = t.map(|p| [p[x],p[y]]);
        let w = crate::geom2d::orientation(p[0],p[1],p[2]);
        w != 0 && (0..3).all(|i| crate::geom2d::orientation(p[i],p[(i+1)%3],
            [point[x],point[y]]) == w)
    }).count()
}

#[test]
fn issue_7292_actual_supported_fold_survives_final_consolidation_adoption() {
    let raw = actual_source();
    // Strict interior of the actual lower S-Q-R cell, with exact dyadic
    // barycentrics(1/2,1/4,1/4). Flattening the pair loses this finite point.
    let t = SOURCE[31].map(|p| p.map(|b| f64::from(f32::from_bits(b))));
    let point = [0,1,2].map(|k| (2.0*t[0][k] + t[1][k] + t[2][k])/4.0);
    assert_eq!(strict_hits(&raw,point),1,"actual source contains the finite witness");
    let output = ClippingProcessor::with_unit_scale(0.001).consolidate(raw);
    assert_eq!(strict_hits(&output,point),1,"final adoption must retain the certified finite fold");
}
