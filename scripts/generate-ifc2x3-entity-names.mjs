/**
 * Generate `rust/export/src/generated/ifc2x3_entity_names.rs`: every entity
 * name IFC2X3 declares, for `rust/export/src/schema_convert.rs`'s "does this
 * (possibly renamed) type have ANY representation at all in IFC2X3" check
 * (#5116).
 *
 * WHY THIS EXISTS. `packages/export/src/schema-converter.ts`'s `convertRecord`
 * already answers this question by looking up the (renamed) type in
 * `attrNameTable('IFC2X3')` — built from `packages/data/src/ifc-schema/
 * generated/entities-ifc2x3.ts` — and falling back to `resolveUnrepresentedEntity`
 * (an `IFCPROXY` for a rooted type, a thrown error for a non-rooted one)
 * when the lookup misses. `rust/export/src/schema_convert.rs` had no
 * equivalent table at all: any type its small hand-maintained rename table
 * (`map_4_to_2x3`) and 4-entry alignment allowlist (`should_skip_entity`)
 * didn't cover passed through byte-for-byte unchanged, silently producing an
 * invalid IFC2X3 file. This table is the missing half — a plain name lookup
 * is enough here, unlike `ifc2x3_required_slots.rs`, because the Rust
 * converter's rename/trim/remap tables already carry the target attribute
 * SHAPES by hand; this only needs to answer "does this name exist in IFC2X3
 * at all", not "what are its attributes".
 *
 * SOURCE OF TRUTH: `packages/data/src/ifc-schema/generated/entities-ifc2x3.ts`
 * (`ENTITIES_IFC2X3`) — the exact table the TypeScript converter reads for
 * the same question. Parsed with the source-text regex `parseEntityTable`
 * shared `parseEntityTable` helper, not `import()`: no
 * enum/type resolution is needed here, so there is no reason to pay for a
 * `tsx` re-exec.
 *
 * Abstract entities are included, same policy as `LEGACY_ROOTED_TYPES` and
 * the TypeScript `attrNameTable`: a STEP record's type is always concrete in
 * practice, but this is a plain "does the schema declare this name" lookup,
 * not a products-only question, so filtering abstractness would only make
 * the two languages disagree for no benefit.
 *
 * Run: `node scripts/generate-ifc2x3-entity-names.mjs` to write the file,
 * `--check` to verify it is up to date.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseEntityTable } from './lib/entity-table.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_REL = 'packages/data/src/ifc-schema/generated/entities-ifc2x3.ts';
const OUT_REL = 'rust/export/src/generated/ifc2x3_entity_names.rs';

function computeNames() {
  const table = parseEntityTable(readFileSync(join(ROOT, SRC_REL), 'utf8'));
  return [...table.keys()].map((n) => n.toUpperCase()).sort();
}

function render(names) {
  let code = `// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

//! Auto-generated: every entity name IFC2X3 declares.
//!
//! Generated by \`scripts/generate-ifc2x3-entity-names.mjs\` from
//! \`packages/data/src/ifc-schema/generated/entities-ifc2x3.ts\` — the same
//! table \`packages/export/src/schema-converter.ts\`'s \`attrNameTable('IFC2X3')\`
//! builds from, for the same "does this type have any representation in
//! IFC2X3 at all" question (#5116).
//!
//! DO NOT EDIT - regenerate with
//!   node scripts/generate-ifc2x3-entity-names.mjs

/// Every IFC2X3 entity name (including abstract ones), UPPERCASE and sorted
/// for binary search.
pub static IFC2X3_ENTITY_NAMES: &[&str] = &[
`;
  for (const name of names) {
    code += `    "${name}",\n`;
  }
  code += '];\n';
  return code;
}

function generate() {
  const names = computeNames();
  if (names.length < 500) {
    throw new Error(`only ${names.length} entity names extracted from ${SRC_REL} — the extractor has drifted`);
  }
  return { names, code: render(names) };
}

if (process.argv[1] && process.argv[1].endsWith('generate-ifc2x3-entity-names.mjs')) {
  const { names, code } = generate();
  if (process.argv.includes('--check')) {
    let current;
    try {
      current = readFileSync(join(ROOT, OUT_REL), 'utf8');
    } catch {
      console.error(`❌ ${OUT_REL} is missing. Run: node scripts/generate-ifc2x3-entity-names.mjs`);
      process.exit(1);
    }
    if (current !== code) {
      console.error(`❌ ${OUT_REL} is out of date. Run: node scripts/generate-ifc2x3-entity-names.mjs`);
      process.exit(1);
    }
    console.log(`✅ ${OUT_REL} is up to date (${names.length} IFC2X3 entity names).`);
  } else {
    mkdirSync(dirname(join(ROOT, OUT_REL)), { recursive: true });
    writeFileSync(join(ROOT, OUT_REL), code);
    console.log(`Wrote ${OUT_REL}: ${names.length} IFC2X3 entity names.`);
  }
}
