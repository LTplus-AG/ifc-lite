/** Property names and value types shared by the IFC2X3 upgrade writers (#10797). */
import { readFileSync, writeFileSync } from 'node:fs';
import { getPropertySetsIfc4 } from '../packages/data/src/ifc-schema/generated/psets-ifc4.ts';
import { SCHEMA_REGISTRY as IFC2X3 } from '../packages/parser/src/generated/ifc2x3/schema-registry.ts';
import { SCHEMA_REGISTRY as IFC4 } from '../packages/parser/src/generated/schema-registry.ts';
import { SCHEMA_REGISTRY as IFC4X3 } from '../packages/parser/src/generated/ifc4x3/schema-registry.ts';

const preferred = {
  IfcFuelProperties: 'Pset_MaterialFuel',
  IfcGeneralMaterialProperties: 'Pset_MaterialCommon',
  IfcGeneralProfileProperties: 'Pset_ProfileMechanical',
  IfcHygroscopicMaterialProperties: 'Pset_MaterialHygroscopic',
  IfcMechanicalConcreteMaterialProperties: 'Pset_MaterialConcrete',
  IfcMechanicalMaterialProperties: 'Pset_MaterialMechanical',
  IfcMechanicalSteelMaterialProperties: 'Pset_MaterialSteel',
  IfcOpticalMaterialProperties: 'Pset_MaterialOptical',
  IfcProductsOfCombustionProperties: 'Pset_MaterialCombustion',
  IfcRibPlateProfileProperties: null,
  IfcStructuralProfileProperties: 'Pset_ProfileMechanical',
  IfcStructuralSteelProfileProperties: 'Pset_ProfileMechanical',
  IfcThermalMaterialProperties: 'Pset_MaterialThermal',
  IfcWaterProperties: 'Pset_MaterialWater',
};

function valueMembers(registry) {
  const members = new Set();
  const pending = ['IfcValue'];
  while (pending.length) {
    const type = pending.pop();
    if (members.has(type)) continue;
    members.add(type);
    pending.push(...(registry.selects[type] ?? []));
  }
  return members;
}

function primitiveOf(type) {
  const seen = new Set();
  while (IFC2X3.types[type] && !seen.has(type)) {
    seen.add(type);
    type = IFC2X3.types[type];
  }
  if (type === 'REAL' || type === 'NUMBER') return 'number';
  if (type === 'BOOLEAN') return 'boolean';
  if (/^STRING(?:\s*\(|$)/.test(type)) return 'text';
}

const templates = new Map(getPropertySetsIfc4().map((template) => [template.name, template]));
const targetMembers = [valueMembers(IFC4), valueMembers(IFC4X3)];
const primitiveKinds = { number: 'Number', boolean: 'Boolean', text: 'Text' };

const rows = Object.entries(preferred).map(([type, main]) => {
  const entity = IFC2X3.entities[type];
  const attrs = entity.allAttributes ?? entity.attributes;
  const groups = new Map();
  if (main) groups.set(main, []);
  const inherited = ['IfcMechanicalConcreteMaterialProperties', 'IfcMechanicalSteelMaterialProperties'].includes(type)
    ? 'Pset_MaterialMechanical'
    : undefined;
  attrs.forEach((attribute, index) => {
    if (['Material', 'ProfileDefinition', 'ProfileName'].includes(attribute.name)) return;
    const valueType = attribute.type === 'BOOLEAN' ? 'IfcBoolean' : attribute.type;
    const kind = primitiveOf(attribute.type);
    if (attribute.isList || attribute.isSet || attribute.isArray || !kind || !targetMembers.every((m) => m.has(valueType))) return;
    const name = attribute.name === 'PhysicalWeight' ? 'MassPerLength' : attribute.name;
    // Use a standard template only when it declares the property with the same
    // value type. Other scalar measures use the original IFC2X3 class name.
    const group = [main, inherited].find((template) =>
      template && templates.get(template)?.properties.some((p) => p.name === name && p.dataType === valueType)) ?? type;
    const fields = groups.get(group) ?? [];
    fields.push({ index, name: group === type ? attribute.name : name, sourceName: attribute.name, valueType: valueType.toUpperCase(), kind });
    groups.set(group, fields);
  });
  return [type.toUpperCase(), attrs.length, [...groups].filter(([, fields]) => fields.length)];
}).sort(([a], [b]) => a.localeCompare(b));

const ts = [
  '/* SPDX-License-Identifier: MPL-2.0 */',
  '// Generated by scripts/generate-ifc2x3-typed-properties.mjs.',
  '',
  'type Field = { index: number; name: string; sourceName: string; valueType: string; kind: "number" | "boolean" | "text" };',
  'type Row = readonly [type: string, arity: number, groups: readonly (readonly [set: string, fields: readonly Field[]])[]];',
  'export const IFC2X3_TYPED_PROPERTIES: readonly Row[] = [',
  ...rows.flatMap(([type, arity, groups]) => [
    `  ['${type}', ${arity}, [`,
    ...groups.map(([group, fields]) => `    ['${group}', ${JSON.stringify(fields)}],`),
    '  ]],',
  ]),
  '];', '',
].join('\n');

const rust = [
  '// SPDX-License-Identifier: MPL-2.0',
  '//! Generated by scripts/generate-ifc2x3-typed-properties.mjs.',
  '',
  'use crate::schema_typed_properties::{Field, Kind, Row};',
  '',
  'pub(crate) static IFC2X3_TYPED_PROPERTIES: &[Row] = &[',
  ...rows.flatMap(([type, arity, groups]) => [
    `    ("${type}", ${arity}, &[`,
    ...groups.flatMap(([group, fields]) => [
      `        ("${group}", &[`,
      ...fields.map(({ index, name, valueType, kind }) => `            Field(${index}, "${name}", "${valueType}", Kind::${primitiveKinds[kind]}),`),
      '        ]),',
    ]),
    '    ]),',
  ]),
  '];', '',
].join('\n');

for (const [path, text] of [
  ['packages/export/src/generated/ifc2x3-typed-properties.ts', ts],
  ['rust/export/src/generated/ifc2x3_typed_properties.rs', rust],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== text) {
      console.error(`${path} is out of date. Run node --import tsx scripts/generate-ifc2x3-typed-properties.mjs.`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, text);
  }
}
