/**
 * Generate `docs/architecture/structural-coverage-ledger.md` from the newest
 * scorer summary in `tests/structural-coverage/baseline/` (or `--summary`).
 *
 * Rows come from the catalogue derived from the generated schema tables;
 * statuses come from the summary the probes produced, never typed by hand.
 * A summary whose rows differ from the derived catalogue, an empty summary, or
 * an offline summary is refused rather than rendered.
 *
 * Usage:
 *   node scripts/generate-structural-coverage-ledger.mjs            # write
 *   node scripts/generate-structural-coverage-ledger.mjs --check    # fail if the committed ledger is stale
 *   --summary <file>  render another summary; --root <dir> read and write another tree (tests)
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENTITY_LEVELS, LEVELS, SCHEMAS, deriveCatalogue } from '../tests/structural-coverage/catalogue.mjs';
import { SUMMARY_SCHEMA as SCHEMA, verifyTotals } from '../tests/structural-coverage/score.mjs';

const flag = (name) => { const i = process.argv.indexOf(name); return i !== -1 ? process.argv[i + 1] : null; };
const ROOT = flag('--root') ? resolve(flag('--root')) : join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_REL = 'docs/architecture/structural-coverage-ledger.md';
const BASELINE_REL = 'tests/structural-coverage/baseline';
const ICON = { pass: '✅', partial: '◐', fail: '❌', error: '❌', skip: '⏸', unwritten: '·' };

function fail(message) {
  console.error(`structural-coverage-ledger: ${message}`);
  process.exit(1);
}

function readJson(path) {
  if (!existsSync(path)) fail(`missing ${relative(ROOT, path)}`);
  try { return JSON.parse(readFileSync(path, 'utf8')); } catch (e) { return fail(`${relative(ROOT, path)} is not JSON: ${e.message}`); }
}

/** The baseline with the highest round number (`r<N>.json`). */
function latestBaseline() {
  const dir = join(ROOT, BASELINE_REL);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^r\d+\.json$/.test(f)) : [];
  if (!files.length) fail(`no r<N>.json summary in ${BASELINE_REL}/`);
  files.sort((a, b) => Number(b.slice(1, -5)) - Number(a.slice(1, -5)));
  return `${BASELINE_REL}/${files[0]}`;
}

const summaryPath = flag('--summary') ? relative(ROOT, resolve(ROOT, flag('--summary'))).split('\\').join('/') : latestBaseline();
const summary = readJson(join(ROOT, summaryPath));
if (summary.schema !== SCHEMA) fail(`${summaryPath} is not an ${SCHEMA} summary`);
if (!Array.isArray(summary.rows) || !summary.rows.length) fail(`${summaryPath} has no rows; refusing to render an empty ledger`);
if (summary.offline) fail(`${summaryPath} was scored offline (${summary.absent.length} corpus file(s) absent); a ledger is only rendered from a complete run`);
const { rows } = deriveCatalogue(ROOT);
const derived = new Set(rows.map((r) => r.id));
const scored = new Set(summary.rows.map((r) => r.id));
const extra = [...scored].filter((id) => !derived.has(id));
const missing = [...derived].filter((id) => !scored.has(id));
if (extra.length || missing.length) {
  fail(`${summaryPath} does not match the derived catalogue (${missing.length} rows missing, ${extra.length} unknown, e.g. ${[...missing, ...extra].slice(0, 4).join(', ')}); re-run tests/structural-coverage/score.mjs`);
}

const forged = verifyTotals(summary);
if (forged.length) fail(`${summaryPath}: its stored totals disagree with its rows; re-run tests/structural-coverage/score.mjs:\n  ${forged.slice(0, 5).join('\n  ')}`);

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const clip = (text, n) => (text.length > n ? `${text.slice(0, n - 1)}…` : text);
const icon = (c) => (c.applicable === false ? '–' : ICON[c.status] ?? '❌');
const ROW = { met: '✅ met', partial: '◐ partial', missing: '❌ missing' };

function why(row) {
  const parts = [];
  for (const level of LEVELS) {
    const c = row.levels[level];
    if (!c || c.applicable === false || c.status === 'pass' || c.status === 'unwritten') continue;
    parts.push(`**${level}** ${c.status}: ${clip(c.reason ?? 'no reason given', 200)}`);
  }
  return cell(parts.join('<br>'));
}

function render() {
  const t = summary.total;
  const lines = [];
  lines.push('# Structural coverage ledger');
  lines.push('');
  lines.push('<!-- GENERATED by scripts/generate-structural-coverage-ledger.mjs. Do not edit by hand: run `node scripts/generate-structural-coverage-ledger.mjs`; `--check` fails when this file is stale. -->');
  lines.push('');
  lines.push('The scorecard of the structural domain hill climb ([#9668](https://github.com/LTplus-AG/ifc-lite/issues/9668)): one row per concrete entity of the IFC structural analysis domain per schema, derived from the generated schema tables, plus capability rows. Every status below comes from a probe that ran (`tests/structural-coverage/`), never from a typed opinion.');
  lines.push('');
  if (summary.cells.score < summary.cells.max / 2) {
    lines.push(`**Most of this ledger is red, by design.** It measures the whole domain, including the levels the product does not do yet: ${summary.cells.max - summary.cells.score} of ${summary.cells.max} cell points are still owed. A red cell is a measured gap, a \`·\` is a probe not written yet; both score 0.`);
    lines.push('');
  }
  lines.push(`**Total: ${t.score} / ${t.max} rows** (met ${t.met}, partial ${t.partial}, missing ${t.missing}). **Cells: ${summary.cells.score} / ${summary.cells.max}.** A met row counts 1, a partial row 0.5; a passing cell 1, a partial cell 0.5. The score may only go up: \`node tests/structural-coverage/score.mjs --check ${summaryPath}\` fails when the total, the cell score, any row or any cell drops.`);
  lines.push('');
  lines.push('| Level | Score | Pass | Partial | Fail | Skip | Not written |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const [level, v] of Object.entries(summary.levels)) {
    lines.push(`| ${level} | ${v.score} / ${v.max} | ${v.pass} | ${v.partial} | ${v.fail + v.error} | ${v.skip} | ${v.unwritten} |`);
  }
  lines.push('');
  lines.push(`Summary: \`${summaryPath}\`, scored over ${summary.corpus.length} corpus files (\`tests/structural-coverage/corpus.json\`).`);
  lines.push('');
  lines.push('✅ pass · ◐ partial · ❌ fail · ⏸ skip · `·` probe not written yet · – not applicable (the rule is in `notApplicable()` of `tests/structural-coverage/catalogue.mjs`).');
  lines.push('');
  for (const schema of SCHEMAS) {
    lines.push(`## ${schema}`);
    lines.push('');
    lines.push(`| Entity | Family | ${ENTITY_LEVELS.join(' | ')} | Row | Why not met (measured levels) |`);
    lines.push(`|---|---|${ENTITY_LEVELS.map(() => '---').join('|')}|---|---|`);
    for (const r of summary.rows.filter((x) => x.kind === 'entity' && x.schema === schema)) {
      lines.push(`| \`${r.entity}\` | ${r.family} | ${ENTITY_LEVELS.map((l) => icon(r.levels[l])).join(' | ')} | ${ROW[r.status]} | ${why(r)} |`);
    }
    lines.push('');
  }
  lines.push('## Capabilities');
  lines.push('');
  lines.push('| Capability | Round | Status | Probe | Why not met |');
  lines.push('|---|---|---|---|---|');
  for (const r of summary.rows.filter((x) => x.kind === 'capability')) {
    const c = r.levels.capability;
    lines.push(`| ${cell(r.title)} (\`${r.id}\`) | ${r.round} | ${icon(c)} | \`${c.probe}\` | ${c.status === 'pass' ? '' : cell(clip(c.reason ?? '', 240))} |`);
  }
  lines.push('');
  lines.push('## Regenerating');
  lines.push('');
  lines.push('```bash');
  lines.push('node tests/structural-coverage/score.mjs   # names the fetch command for any absent corpus file, then exits 2');
  lines.push('node tests/structural-coverage/score.mjs --out tests/structural-coverage/.out/summary.json --check ' + summaryPath);
  lines.push('cp tests/structural-coverage/.out/summary.json tests/structural-coverage/baseline/r<N>.json   # only when a round is accepted');
  lines.push('node scripts/generate-structural-coverage-ledger.mjs');
  lines.push('```');
  return lines.join('\n') + '\n';
}

const content = render();
const target = join(ROOT, OUT_REL);
if (process.argv.includes('--check')) {
  const existing = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (existing !== content) {
    console.error(`❌ ${OUT_REL} is stale against ${summaryPath}.`);
    console.error('   fix: node scripts/generate-structural-coverage-ledger.mjs   (then commit the file)');
    process.exit(1);
  }
  console.log(`✅ ${OUT_REL} is up to date (${summary.total.score} / ${summary.total.max} rows, ${summary.cells.score} / ${summary.cells.max} cells).`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  console.log(`Wrote ${OUT_REL} from ${summaryPath}: ${summary.total.score} / ${summary.total.max} rows`);
}
