/** Build-time evaluation only; the runtime catalogue imports no feature implementations. */
import '../apps/viewer/src/test/setup-dom.js';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { operationModules } from '../apps/viewer/src/lib/agent-tools/operations/modules';
import { compileOperationSchema } from '../apps/viewer/src/lib/agent-tools/operations/validators';
import { clashControlBindings } from '../apps/viewer/src/lib/agent-tools/operations/clash-native-inventory';
import { coreControlInventory } from '../apps/viewer/src/lib/agent-tools/operations/core-inventory';
import { analyticsControlInventory } from '../apps/viewer/src/lib/agent-tools/operations/analytics-inventory';
import { coordinationControlInventory } from '../apps/viewer/src/lib/agent-tools/operations/coordination-inventory';
import { appearanceNativeControlBindings } from '../apps/viewer/src/lib/agent-tools/operations/appearance-native-inventory';
import { EXPORT_COMMAND_IDS } from '../apps/viewer/src/components/viewer/toolbar/export-commands';
import { nativeExportRegistryInventory } from '../apps/viewer/src/lib/agent-tools/operations/export-native-inventory';
import { toolControlAudits } from '../apps/viewer/src/lib/agent-tools/operations/coverage-audit';
import { authoringControlBindings } from '../apps/viewer/src/lib/agent-tools/operations/authoring-inventory';
import type { Operation } from '../apps/viewer/src/lib/agent-tools/operations/contract';

const directory = new URL('../apps/viewer/src/lib/agent-tools/operations/', import.meta.url);
const contracts: Array<Record<string, unknown>> = [];
const seen = new Set<string>();
for (const { module, exportName } of operationModules) {
  const loaded: Record<string, unknown> = await import(new URL(`${module}.ts`, directory).href);
  const entries = loaded[exportName];
  if (!Array.isArray(entries)) throw new Error(`Missing operation array: ${module}.${exportName}`);
  for (const entry of entries as Operation[]) {
    if (!entry.id || seen.has(entry.id)) throw new Error(`Missing or duplicate operation ID: ${entry.id}`);
    if (!entry.inputSchema || !entry.outputSchema || !entry.effects.length) throw new Error(`Incomplete contract: ${entry.id}`);
    try { compileOperationSchema(entry.inputSchema); compileOperationSchema(entry.outputSchema); }
    catch (error) { throw new Error(`Invalid schema for ${entry.id}`, { cause: error }); }
    seen.add(entry.id);
    const { id, version, owner, features, description, needs, effects, capability, inputSchema, outputSchema, result, completion, implementation, policy, candidateOnly } = entry;
    contracts.push({ id, version, owner, features, description, needs, effects, capability, inputSchema, outputSchema, result, completion, implementation, policy, candidateOnly, module, exportName });
  }
}
const bindings = [
  ...clashControlBindings.flatMap(row => row.operations),
  ...coreControlInventory.flatMap(row => row.controls.flatMap(control => control.operations)),
  ...analyticsControlInventory.flatMap(row => row.controls.flatMap(control => control.operations)),
  ...coordinationControlInventory.flatMap(row => row.operations),
  ...authoringControlBindings.flatMap(row => row.operations),
  ...appearanceNativeControlBindings.flatMap(row => row.operations),
  ...nativeExportRegistryInventory.flatMap(row => row.operations),
  ...Object.values(toolControlAudits).flatMap(row => row.operations),
];
for (const id of bindings) if (!seen.has(id)) throw new Error(`Control inventory refers to an unregistered operation: ${id}`);
const header = '/* This Source Code Form is subject to the terms of the Mozilla Public\n * License, v. 2.0. If a copy of the MPL was not distributed with this\n * file, You can obtain one at https://mozilla.org/MPL/2.0/. */\n\n// @generated by scripts/generate-viewer-operations.ts; do not edit.\n';
const data = header + 'import type { OperationContract } from \'../metadata\';\nexport const operationContracts: readonly OperationContract[] = ' + JSON.stringify(contracts, null, 2) + ';\n';
const loaders = header + 'export const operationLoaders: Record<string, () => Promise<Record<string, unknown>>> = {\n' + [...new Set(operationModules.map(entry => entry.module))].map(module => `  '${module}': () => import('../${module}'),`).join('\n') + '\n};\n';
// Keep coverage discovery independent of the toolbar's dialog implementations.
const exportIds = header + 'export const toolbarExportIds: readonly string[] = ' + JSON.stringify(EXPORT_COMMAND_IDS, null, 2) + ';\n';
const check = process.argv.includes('--check');
if (!check) mkdirSync(new URL('generated/', directory), { recursive: true });
for (const [name, content] of [['generated/contracts.ts', data], ['generated/loaders.ts', loaders], ['generated/export-command-ids.ts', exportIds]]) {
  const target = new URL(name, directory);
  if (check) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Stale ${name}; run pnpm viewer:operations:update.`);
  } else writeFileSync(target, content);
}
console.log(`Viewer operations: ${contracts.length} contracts from ${operationModules.length} native arrays${check ? ' verified' : ' generated'}.`);
