import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { digest, verifyExecutable, extractPinnedExecutable, publishGenerated, wrapTranslator, releaseProfile } from './lib/imported-artifacts.mjs';

function fixture(run) {
  const root = mkdtempSync(join(tmpdir(), 'imported-fixture-'));
  try { run(root); } finally { rmSync(root, { recursive: true, force: true }); }
}
test('pinned tool extraction rejects altered bytes without replacing the prior executable', () => fixture(root => {
  mkdirSync(join(root, 'sdk/bin'), { recursive: true });
  const bytes = Buffer.from('fixture translator executable');
  writeFileSync(join(root, 'sdk/bin/wasm2js'), bytes);
  const archive = join(root, 'sdk.tar');
  assert.equal(spawnSync('tar', ['-cf', archive, '-C', root, 'sdk']).status, 0);
  const output = join(root, 'tool');
  writeFileSync(output, 'prior good tool');
  assert.throws(() => extractPinnedExecutable(archive, output, digest('different')), /digest mismatch/);
  assert.equal(readFileSync(output, 'utf8'), 'prior good tool');
  extractPinnedExecutable(archive, output, digest(bytes));
  assert.equal(verifyExecutable(output, digest(bytes)), output);
  assert.throws(() => verifyExecutable(output), /digest differs/);
}));

test('translator failure and changed ABI preserve all previous generated bytes', () => fixture(root => {
  const directory = join(root, 'generated');
  mkdirSync(directory);
  writeFileSync(join(directory, 'kernel.js'), 'prior kernel');
  writeFileSync(join(directory, 'provenance.json'), 'prior provenance');
  for (const fail of [() => { throw Error('translator exit 1'); }, () => wrapTranslator('export var memory = {};\n')]) {
    assert.throws(() => publishGenerated(directory, staged => {
      writeFileSync(join(staged, 'kernel.js'), 'partial replacement');
      fail();
    }));
    assert.equal(readFileSync(join(directory, 'kernel.js'), 'utf8'), 'prior kernel');
    assert.equal(readFileSync(join(directory, 'provenance.json'), 'utf8'), 'prior provenance');
    assert.deepEqual(readdirSync(root), ['generated']);
  }
  publishGenerated(directory, staged => writeFileSync(join(staged, 'kernel.js'), 'validated replacement'));
  assert.deepEqual(readdirSync(directory), ['kernel.js']);
  assert.equal(readFileSync(join(directory, 'kernel.js'), 'utf8'), 'validated replacement');
}));

test('wrapped translator remains lazy and runs without dynamic compilation', async () => {
  const translated = ['memory = { buffer: new ArrayBuffer(8) }', 'imported_alloc = length => length', 'imported_free = () => {}', 'imported_run = pointer => pointer + 1'].map(value => `export var ${value};`).join('\n');
  const module = await import(`data:text/javascript,${encodeURIComponent(wrapTranslator(translated))}`);
  const kernel = module.createImportedGeometryKernel();
  assert.equal(kernel.memory.buffer.byteLength, 8);
  assert.equal(kernel.imported_run(kernel.imported_alloc(4)), 5);
});

test('release profile extraction ignores versions, dependencies, comments and other profiles', () => {
  const manifest = (version, extra) => `[workspace.package]\nversion = "${version}"\n${extra}\n[profile.release] # speed\nopt-level = 3\n\n# note\n[profile.release.package."*"]\nstrip = true\n[profile.server-release]\npanic = "unwind"\n`;
  const a = releaseProfile(manifest('1.0.0', '[workspace.dependencies]\nx = "1"'));
  assert.equal(a, releaseProfile(manifest('2.0.0', '')));
  assert.equal(a, '[profile.release]\nopt-level = 3\n[profile.release.package."*"]\nstrip = true');
  assert.notEqual(a, releaseProfile(manifest('1.0.0', '').replace('opt-level = 3', 'opt-level = 2')));
  assert.throws(() => releaseProfile('[workspace]\n'));
});
