// Reuse the authoritative generator; select only the native consumed closure.
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { projections, drift, writeOutputs } from '../retained-contract/generate.mjs';
import { rustWire } from '../retained-contract/rust-wire-generate.mjs';
import { isMainEntry } from '../lib/is-main-entry.mjs';
import { schema } from './schema.mjs';
const root = fileURLToPath(new URL('../..', import.meta.url));
const snake = (text) => text.replace(/([a-z0-9])([A-Z])/gu, '$1_$2').toLowerCase();
const variant = (text) => text.toLowerCase().split('_').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
export async function nativeProjection() {
  const outputs = await projections(schema);
  const full = outputs.get('rust/processing/src/generated/retained_contract.rs');
  const names = new Set();
  const visit = (name) => {
    if (names.has(name)) return;
    names.add(name);
    const node = schema.types[name];
    if (node.kind === 'record') Object.values(node.fields).forEach(visit);
    if (node.kind === 'union') Object.values(node.variants).forEach(visit);
    if (node.kind === 'list') visit(node.item);
  };
  ['Options', 'Binding', 'NativeReport'].forEach(visit);
  const entries = Object.entries(schema.types).filter(([name]) => names.has(name));
  // Select complete declarations emitted by the existing generator, never a
  // handwritten second copy of its options, code enums or scalar validators.
  const declarations = entries.map(([name]) => {
    const pattern = new RegExp(`(?:#\\[derive[^\\n]*\\]\\n(?:#\\[serde[^\\n]*\\]\\n)?(?:struct|enum) ${name} \\{[\\s\\S]*?\\n\\}\\n|type ${name} = [^\\n]*\\n)`, 'u');
    const declaration = full.match(pattern)?.[0];
    if (!declaration) throw new Error(`Missing generated declaration ${name}`);
    return declaration.replace(/^(struct|enum|type) /gmu, 'pub(crate) $1 ')
      .replace(/\] ([a-z_][a-z_0-9]*):/gu, '] pub(crate) $1:');
  }).join('');
  const checks = entries.map(([name]) => {
    const line = full.split('\n').find((line) => line.startsWith(`fn check_${snake(name)}(`));
    if (!line) throw new Error(`Missing generated validator ${name}`);
    return `${line}\n`;
  }).join('');
  const shared = await readFile(new URL('../retained-contract/rust-semantics.txt', import.meta.url), 'utf8');
  const wire = await readFile(new URL('../retained-contract/rust-wire.txt', import.meta.url), 'utf8');
  const semantics = await readFile(new URL('./semantics.txt', import.meta.url), 'utf8');
  const family = full.split('\n').find((line) => line.startsWith('fn cause_family('));
  const combination = `fn native_combination(value: &NativeFailure) -> bool { match value.code {\n${Object.entries(schema.refusalRules).map(([code, rule]) =>
    `Code::${variant(code)} => value.reason == DetailReason::${variant(rule.reason)} && matches!((&value.stage, &value.requirement), ${rule.contexts.map(([stage, requirement]) => `(Stage::${variant(stage)}, Requirement::${variant(requirement)})`).join(' | ')}),`).join('\n')}\n} }\n`;
  const dispatch = rustWire({ ...schema, types: Object.fromEntries(entries) }, ['Options', 'NativeReport'])
    .replace(/fn decode_binding\([\s\S]*?\n\}\n/gu, '')
    .replace('fn decode_native_report(json: &str)', 'fn decode_native_report(json: &str, binding: &Binding)')
    .replace('check_native_report(&value).map_err', 'validate_native(&value, binding).map_err');
  const result = (full.slice(0, full.indexOf('\n', full.indexOf('schema SHA256'))) + '\n'
    + '// Native extension generated by scripts/retained-native-contract/generate.mjs.\n'
    + declarations + checks + family + '\n' + combination
    + shared.slice(0, shared.indexOf('fn unbound_refusal(')) + semantics + wire + dispatch)
    .replace(/^(fn (?:decode_options|decode_native_report|validate_native|check_global_id|text_format|cause_family))\(/gmu, 'pub(crate) $1(');
  return new Map([['rust/processing/src/generated/retained_native_contract.rs', result]]);
}
export async function check() {
  const failures = await drift(root, await nativeProjection());
  if (failures.length) throw new Error(`Native contract drift: ${failures.join(', ')}`);
}
if (isMainEntry(import.meta.url)) {
  if (process.argv.includes('--check')) await check();
  else await writeOutputs(root, await nativeProjection());
}
