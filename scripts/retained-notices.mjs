import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainEntry } from './lib/is-main-entry.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = 'licenses/retained';
const hash = value => createHash('sha256').update(value).digest('hex');
const INPUTS = ['licenses/retained/supplemental.json', 'scripts/build-wasm.sh', 'Cargo.lock', 'rust-toolchain.toml', 'native/smlib-adapter/CMakeLists.txt',
  '.github/actions/setup-wasm-build/action.yml', '.github/workflows/geometry-platform.yml'];
const OUTPUTS = [`${DIR}/THIRD_PARTY_NOTICES.txt`, 'packages/wasm/THIRD_PARTY_NOTICES.txt',
  'packages/cli/THIRD_PARTY_NOTICES.txt'];
function files(root) {
  return readdirSync(root, { withFileTypes: true }).flatMap(entry => {
    const path = join(root, entry.name);
    return entry.isDirectory() ? files(path) : entry.isFile() ? [path] : [];
  }).sort();
}
function inputHashes(root) {
  const manifests = files(join(root, 'rust')).filter(path => path.endsWith('/Cargo.toml'));
  return Object.fromEntries([...INPUTS, 'Cargo.toml', ...manifests.map(path => relative(root, path))]
    .sort().map(path => [path, hash(readFileSync(join(root, path)))]));
}
export function renderNotices(manifest, readText) {
  const chunks = ['IFC-Lite retained artifact third-party notices\nGenerated by scripts/retained-notices.mjs.\n'
    + 'Conservative source/build dependency inventory; not a link map or legal approval.\n'
    + 'See docs/architecture/retained-licensing.md for scope and unresolved release questions.\n'];
  const included = new Set();
  for (const component of manifest.components) {
    chunks.push(`\n=== ${component.name} ${component.version} ===\nLicence declaration: ${component.license}\nSource: ${component.source}\nScope: ${component.scope}\n`);
    if (!component.notices.length) chunks.push('OPEN: upstream package contains no licence text; obtain authoritative notice before release.\n');
    for (const notice of component.notices) {
      const text = readText(notice.file);
      if (hash(text) !== notice.sha256) throw new Error(`Notice input hash mismatch: ${notice.file}`);
      chunks.push(`\n--- ${notice.origin} (sha256 ${notice.sha256}) ---\n`);
      chunks.push(included.has(notice.sha256) ? 'Full text reproduced above under this SHA-256.\n' : `${text}\n`);
      included.add(notice.sha256);
    }
  }
  return chunks.join('');
}
export function checkNotices(root = ROOT, check = true) {
  const manifest = JSON.parse(readFileSync(join(root, DIR, 'manifest.json')));
  if (JSON.stringify(manifest.inputs) !== JSON.stringify(inputHashes(root))) {
    throw new Error('Retained notice inventory inputs changed; refresh against pinned SDK, toolchain and Cargo metadata');
  }
  const output = renderNotices(manifest, path => readFileSync(join(root, DIR, path), 'utf8'));
  for (const path of OUTPUTS) {
    if (check) {
      if (!existsSync(join(root, path)) || readFileSync(join(root, path), 'utf8') !== output) throw new Error(`Notice drift: ${path}`);
    } else writeFileSync(join(root, path), output);
  }
}
function refresh({ sdk, emscripten, metadata }, root = ROOT) {
  const revision = readFileSync(join(root, 'native/smlib-adapter/CMakeLists.txt'), 'utf8')
    .match(/set\(IFCLITE_SMLIB_REVISION ([a-f0-9]{40})\)/)[1];
  const git = (...args) => execFileSync('git', ['-C', sdk, ...args], { encoding: 'utf8' }).trim();
  if (git('rev-parse', 'HEAD') !== revision || git('status', '--porcelain', '--untracked-files=all', '--ignored', '--',
    'source/SMLib', 'source/SM_API', 'LICENSE', 'THIRD_PARTY_NOTICES.md')) throw new Error('SDK pin/cleanliness mismatch');
  if (JSON.parse(readFileSync(join(emscripten, 'emscripten-version.txt'), 'utf8')) !== '4.0.15') throw new Error('Expected Emscripten 4.0.15');
  mkdirSync(join(root, DIR, 'texts'), { recursive: true });
  const components = [];
  function add(name, version, license, source, scope, base, paths) {
    const notices = paths.map(path => {
      const bytes = readFileSync(join(base, path));
      const sha256 = hash(bytes), file = `texts/${sha256}.txt`;
      writeFileSync(join(root, DIR, file), bytes);
      return { origin: path, file, sha256 };
    });
    components.push({ name, version, license, source, scope, notices });
  }
  add('NVIDIA usd-brep SMLib + SM_API', revision, 'Apache-2.0 (kernel/API)',
    `https://github.com/NVIDIA-Omniverse/usd-brep/tree/${revision}`, 'native worker and Emscripten SDK module; full upstream notices retained conservatively',
    sdk, ['LICENSE', 'THIRD_PARTY_NOTICES.md']);
  add('Emscripten runtime (including Node path portions)', '4.0.15', 'MIT OR NCSA',
    'https://github.com/emscripten-core/emscripten/tree/4.0.15', 'SMLib wasm/JS, CLI engine; compiler tools are not shipped', emscripten, ['LICENSE']);
  for (const [name, path, license] of [
    ['musl', 'libc/musl/COPYRIGHT', 'MIT AND BSD variants (see text)'],
    ['libc++', 'libcxx/LICENSE.TXT', 'Apache-2.0 WITH LLVM-exception AND legacy notices'],
    ['libc++abi', 'libcxxabi/LICENSE.TXT', 'Apache-2.0 WITH LLVM-exception AND legacy notices'],
    ['libunwind', 'libunwind/LICENSE.TXT', 'Apache-2.0 WITH LLVM-exception AND legacy notices'],
    ['compiler-rt', 'compiler-rt/LICENSE.TXT', 'Apache-2.0 WITH LLVM-exception AND legacy notices'],
    ['llvm-libc', 'llvm-libc/LICENSE.TXT', 'Apache-2.0 WITH LLVM-exception'],
  ]) add(name, 'bundled with Emscripten 4.0.15', license,
    `https://github.com/emscripten-core/emscripten/tree/4.0.15/system/lib/${path}`,
    'conservative runtime inventory; final linker map must identify used portions', join(emscripten, 'system/lib'), [path]);
  const allocatorPath = join(emscripten, 'system/lib/dlmalloc.c');
  const allocatorBytes = readFileSync(allocatorPath);
  const allocatorNotice = allocatorBytes.toString().match(/ This is a version \(aka dlmalloc\)[\s\S]*?(?= \* Quickstart)/)?.[0];
  if (!allocatorNotice) throw new Error('dlmalloc licence/version header changed');
  const allocatorHash = hash(allocatorNotice), allocatorFile = `texts/${allocatorHash}.txt`;
  writeFileSync(join(root, DIR, allocatorFile), allocatorNotice);
  components.push({ name: 'dlmalloc', version: '2.8.6 (Emscripten 4.0.15)',
    license: 'Public domain / CC0-1.0 dedication in source',
    source: 'https://github.com/emscripten-core/emscripten/blob/4.0.15/system/lib/dlmalloc.c',
    scope: 'Default SMLib WASM allocator; Emscripten modifications covered by Emscripten licence',
    sourceFileSha256: hash(allocatorBytes),
    notices: [{ origin: 'system/lib/dlmalloc.c licence/version header', file: allocatorFile, sha256: allocatorHash }] });
  const data = JSON.parse(readFileSync(metadata));
  const packages = new Map(data.packages.map(p => [p.id, p]));
  const nodes = new Map(data.resolve.nodes.map(n => [n.id, n]));
  const seen = new Set();
  function visit(id) {
    if (seen.has(id)) return;
    seen.add(id);
    for (const dep of nodes.get(id).deps) if (dep.dep_kinds.some(k => k.kind !== 'dev')) visit(dep.pkg);
  }
  visit(data.packages.find(p => p.name === 'ifc-lite-wasm').id);
  for (const id of [...seen].sort()) {
    const pkg = packages.get(id);
    if (!pkg.source) continue;
    const base = dirname(pkg.manifest_path);
    const paths = files(base).filter(path => /^(LICENSE|COPYING|COPYRIGHT|NOTICE)/i.test(path.split('/').at(-1)))
      .map(path => relative(base, path));
    add(pkg.name, pkg.version, pkg.license ?? 'OPEN: no licence declaration', pkg.source,
      'pkg-retained Rust/wasm-bindgen closure (workspace-unified superset, includes build tools)', base, paths);
  }
  const sysroot = execFileSync('rustc', ['--print', 'sysroot'], { cwd: root, encoding: 'utf8' }).trim();
  const rustDocs = join(sysroot, 'share/doc/rust');
  add('Rust standard library', execFileSync('rustc', ['--version'], { cwd: root, encoding: 'utf8' }).trim(),
    'MIT OR Apache-2.0 plus bundled components', 'https://github.com/rust-lang/rust',
    'pkg-retained wasm; COPYRIGHT-library.html enumerates bundled library components', rustDocs,
    ['COPYRIGHT-library.html', ...files(join(rustDocs, 'licenses')).map(path => relative(rustDocs, path))]);
  for (const supplement of JSON.parse(readFileSync(join(root, DIR, 'supplemental.json')))) {
    const component = components.find(c => c.name === supplement.name && c.version === supplement.version);
    if (!component) throw new Error(`Stale supplemental notice: ${supplement.name}`);
    component.notices.push(...supplement.notices);
  }
  const manifest = { format: 1, inputs: inputHashes(root), components };
  writeFileSync(join(root, DIR, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
}
if (isMainEntry(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args[0] === '--refresh') {
      const options = {};
      for (let i = 1; i < args.length; i += 2) options[args[i].replace(/^--/, '')] = args[i + 1];
      if (!options.sdk || !options.emscripten || !options.metadata) throw new Error('--refresh requires --sdk ABS --emscripten ABS --metadata ABS');
      refresh(options);
    }
    checkNotices(ROOT, args[0] !== '--refresh' && args[0] !== '--write');
    console.log('Retained notice inventory and generated bundles match; human release review remains required.');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
